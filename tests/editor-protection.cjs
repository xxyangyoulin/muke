const assert = require('node:assert/strict');
const {execFileSync} = require('node:child_process');
const {openPage} = require('./cdp.cjs');

(async () => {
 const [base, root] = process.argv.slice(2);
 const sql = query => execFileSync('sqlite3', ['-cmd', '.timeout 5000', root + '/var/blog.sqlite', query], {encoding:'utf8'}).trim();
 sql("INSERT INTO articles(title,content,tags,created_at,updated_at) VALUES('editor-protection-test','server original','原标签','2020','2020')");
 const id = Number(sql("SELECT id FROM articles WHERE title='editor-protection-test'"));
 const page = await openPage(base);
 const wait = (ms=850) => new Promise(resolve=>setTimeout(resolve,ms));
 const openEditor = async (articleId=id) => {
  await page.evalJs(`(async()=>{const {store}=await import('/assets/lib/store.js');const {apiGet}=await import('/assets/lib/api.js');store.editingArticle=${articleId === null ? "'new'" : `(await apiGet('articles',{id:${articleId}})).article`};store.editorFormat='md';store.page='admin';const {admin}=await import('/assets/views/admin.js');admin();})()`);
 };
 const fill = async (selector, value) => page.evalJs(`{const el=document.querySelector(${JSON.stringify(selector)});el.value=${JSON.stringify(value)};el.dispatchEvent(new Event('input',{bubbles:true}));}`);
 const cached = async (articleId=id) => page.evalJs(`JSON.parse(localStorage.getItem('muke:article-draft:${articleId ?? 'new'}') || 'null')`);
 const warns = async () => page.evalJs(`{const event=new Event('beforeunload',{cancelable:true});window.dispatchEvent(event);event.defaultPrevented;}`);
 try {
  await page.goto(base + '/');
  await page.evalJs(`document.querySelector('a[href="/admin"]').click()`);
  await wait(300);
  await page.evalJs(`document.querySelector('#auth-form input[name=username]').value='tester';document.querySelector('#auth-form input[name=password]').value='Password12345';document.querySelector('#auth-form').requestSubmit()`);
  await wait();
  await openEditor();
  assert.equal(await warns(), false);
  await fill('#article-title','本地新标题');
  await fill('#article-content','未保存正文');
  await fill('#tag-field','新标签');
  await page.evalJs(`document.querySelector('#tag-field').dispatchEvent(new KeyboardEvent('keydown',{key:'Enter',bubbles:true}))`);
  await fill('#tag-field','尚未确认');
  await wait();
  const draft = await cached();
  assert.equal(draft.title, '本地新标题');
  assert.equal(draft.content, '未保存正文');
  assert.equal(draft.tags, '原标签,新标签');
  assert.equal(draft.pendingTag, '尚未确认');
  assert.equal(sql('SELECT content FROM articles WHERE id=' + id), 'server original');
  assert.equal(await warns(), true);
  await page.evalJs(`window.confirm=message=>{window.lastConfirm=message;return false};document.querySelector('#editor-back').click()`);
  assert.ok(await page.evalJs(`!!document.querySelector('#article-content')`));
  await page.evalJs(`document.querySelector('nav a[href="/"]').click()`);
  assert.equal(await page.evalJs(`location.pathname`), '/admin');
  await page.evalJs(`history.back()`);
  await wait(400);
  assert.equal(await page.evalJs(`location.pathname`), '/admin', '取消后退未恢复地址');
  assert.equal(await page.evalJs(`document.querySelector('#article-content').value`), '未保存正文');
  await page.evalJs(`window.confirm=()=>true;history.back()`);
  await wait(400);
  assert.equal(await page.evalJs(`location.pathname`), '/');
  assert.equal(await warns(), false, '离开编辑器后仍拦截刷新');
  await openEditor();
  await page.evalJs(`document.querySelector('[data-draft-restore]').click();window.confirm=()=>false;history.forward()`);
  await wait(400);
  assert.equal(await page.evalJs(`location.pathname`), '/', '取消前进未恢复地址');
  assert.equal(await page.evalJs(`document.querySelector('#article-content').value`), '未保存正文');
  await page.evalJs(`window.confirm=()=>true;history.forward()`);
  await wait(400);
  assert.equal(await page.evalJs(`location.pathname`), '/admin');
  assert.ok(await page.evalJs(`document.querySelector('#editor-recovery').open`));
  assert.equal(await page.evalJs(`document.querySelector('#article-content').value`), 'server original', '未经确认覆盖了编辑器');
  await page.evalJs(`document.querySelector('[data-draft-restore]').click()`);
  assert.equal(await page.evalJs(`document.querySelector('#article-content').value`), '未保存正文');
  assert.equal(await page.evalJs(`document.querySelector('#tag-field').value`), '尚未确认');
  await fill('#tag-field','再加一个');
  await page.evalJs(`document.querySelector('#tag-field').dispatchEvent(new KeyboardEvent('keydown',{key:'Enter',bubbles:true}))`);
  assert.equal(await page.evalJs(`document.querySelectorAll('#tag-chips .tag-chip').length`), 3, '恢复后标签重复绑定');
  await page.evalJs(`document.querySelector('#article-content').setSelectionRange(0,2);document.querySelector('[data-md="**"]').click()`);
  await wait();
  assert.ok((await cached()).content.startsWith('**未保**'), '工具栏修改未暂存');
  await page.evalJs(`window.realFetch=window.fetch;window.fetch=(url,...args)=>String(url).includes('action=save-article')?Promise.resolve(new Response(JSON.stringify({error:'测试保存失败'}),{status:500})):window.realFetch(url,...args);document.querySelector('#article-save').click()`);
  await wait(400);
  assert.ok(await cached(), '失败保存清除了暂存');
  assert.equal(await warns(), true);
  await page.evalJs(`window.fetch=async(url,...args)=>{const response=await window.realFetch(url,...args);if(String(url).includes('action=articles')){window.editorRefreshStarted=true;await new Promise(resolve=>setTimeout(resolve,500));}return response;};document.querySelector('#article-save').click()`);
  for (let n=0;n<20 && !(await page.evalJs(`!!window.editorRefreshStarted`));n++) await wait(50);
  assert.ok(await page.evalJs(`!!window.editorRefreshStarted`));
  await page.evalJs(`document.querySelector('nav a[href="/"]').click()`);
  await wait(1300);
  assert.ok(await page.evalJs(`!!document.querySelector('#post-list')`), '保存刷新结束后强行返回后台');
  await page.evalJs(`window.fetch=window.realFetch`);
  assert.equal(await cached(), null);
  assert.equal(await warns(), false);
  assert.ok(sql('SELECT content FROM articles WHERE id=' + id).startsWith('**未保**'));

  await openEditor();
  await fill('#article-content','刷新恢复内容');
  await wait();
  let beforeUnloadSeen = false;
  const dialogHandler = event => {
   const message = JSON.parse(event.data);
   if (message.method === 'Page.javascriptDialogOpening') {
    if (message.params.type === 'beforeunload') beforeUnloadSeen = true;
    page.send('Page.handleJavaScriptDialog', {accept:true});
   }
  };
  page.ws.addEventListener('message', dialogHandler);
  await page.send('Runtime.evaluate', {expression:`document.querySelector('#article-content').focus()`, userGesture:true});
  await page.send('Page.reload');
  await wait(1600);
  page.ws.removeEventListener('message', dialogHandler);
  await openEditor();
  assert.ok(await page.evalJs(`document.querySelector('#editor-recovery').open`));
  await page.evalJs(`document.querySelector('[data-draft-restore]').click()`);
  assert.equal(await page.evalJs(`document.querySelector('#article-content').value`), '刷新恢复内容');
  assert.ok(beforeUnloadSeen, '刷新未触发原生离开提醒');
  await page.evalJs(`window.confirm=()=>true;document.querySelector('#editor-back').click()`);
  await openEditor();
  await page.evalJs(`document.querySelector('[data-draft-discard]').click()`);
  assert.equal(await cached(), null);
  assert.equal(await warns(), false);
  await page.evalJs(`window.originalSetItem=Storage.prototype.setItem;Storage.prototype.setItem=()=>{throw new DOMException('quota','QuotaExceededError')}`);
  await fill('#article-content','无法暂存的内容');
  await wait();
  assert.ok(await page.evalJs(`document.querySelector('#editor-local-status').textContent.includes('本地暂存失败')`));
  await page.evalJs(`window.confirm=message=>{window.lastConfirm=message;return false};document.querySelector('#editor-back').click()`);
  assert.ok(await page.evalJs(`window.lastConfirm.includes('本地暂存失败')`));
  await page.evalJs(`Storage.prototype.setItem=window.originalSetItem;window.confirm=()=>true;document.querySelector('#editor-back').click()`);
  assert.equal((await cached()).content, '无法暂存的内容');

  await openEditor(null);
  assert.equal(await page.evalJs(`!!document.querySelector('#editor-recovery')`), false, '文章暂存串到新文章');
  await page.evalJs(`document.querySelector('[data-format="html"]').click()`);
  await fill('#article-title','富文本暂存');
  await page.evalJs(`document.querySelector('#article-content').innerHTML='<p><strong>富文本正文</strong></p>';document.querySelector('#article-content').dispatchEvent(new Event('input',{bubbles:true}))`);
  await wait();
  assert.equal((await cached(null)).format, 'html');
  await page.evalJs(`document.querySelector('#editor-back').click()`);
  await page.evalJs(`{const key='muke:article-draft:new',draft=JSON.parse(localStorage.getItem(key));draft.content+='<script>window.unsafeDraft=1</script><img src=x onerror="window.unsafeDraft=1">';localStorage.setItem(key,JSON.stringify(draft));}`);
  await openEditor(null);
  await page.evalJs(`document.querySelector('[data-draft-restore]').click()`);
  assert.equal(await page.evalJs(`document.querySelector('#article-content').tagName`), 'DIV');
  assert.ok(await page.evalJs(`document.querySelector('#article-content strong').textContent==='富文本正文'`));
  assert.equal(await page.evalJs(`document.querySelectorAll('#article-content script,#article-content [onerror]').length`), 0);
  assert.equal(await page.evalJs(`window.unsafeDraft || 0`), 0);
  await page.evalJs(`document.querySelector('#article-draft').click()`);
  await wait();
  assert.equal(await cached(null), null);
  assert.equal(sql("SELECT draft FROM articles WHERE title='富文本暂存'"), '1');
  await openEditor();
  await page.evalJs(`document.querySelector('[data-draft-restore]').click();document.querySelector('#article-delete').click();document.querySelector('#confirm-delete').click()`);
  await wait();
  assert.equal(await cached(), null);
  assert.equal(sql('SELECT COUNT(*) FROM articles WHERE id=' + id), '0');
  assert.deepEqual(page.errors, []);
  console.log('editor-protection: 离开/刷新/后退保护、恢复/丢弃、标签/工具栏、存储失败、保存失败保留、成功清理及富文本恢复通过');
 } finally {
  page.close();
  sql(`DELETE FROM article_revisions WHERE article_id=${id} OR article_id IN (SELECT id FROM articles WHERE title='富文本暂存');DELETE FROM articles WHERE id=${id} OR title='富文本暂存';`);
 }
})().catch(error=>{console.error(error);process.exitCode=1;});
